#!/usr/bin/env node
/**
 * sync-orchestrator-agents — render one agent definition per orchestrator lane.
 *
 * Adding a lane should cost one JSON entry, not one JSON entry plus a hand-written
 * agent that slowly drifts from it. Everything lane-specific in these agents is
 * already declared in `lib/data/orchestrator-lanes.json`; the shared protocol
 * lives in `skills/persona-lab/references/orchestrator-protocol.md`. This script
 * is the join, and `test/orchestrator.test.mjs` re-renders and byte-compares, so
 * an edit to either side that is not reflected in the other fails the suite
 * instead of shipping.
 *
 *   node scripts/sync-orchestrator-agents.mjs [--check]
 *
 * The fallback lane (`general`) is deliberately NOT generated. It routes between
 * lanes rather than describing one discipline, so its agent is hand-written.
 *
 * Node, ESM, no dependencies.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { listLanes } from '../lib/orchestrator.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));

export const GENERATED_LANES = listLanes().filter((lane) => lane.fallback !== true);

const PROTOCOL = 'skills/persona-lab/references/orchestrator-protocol.md';

function agentName(lane) {
  return path.basename(lane.agent_file, '.md');
}

/** The `description` is the trigger: when a host should reach for this agent at all. */
function description(lane) {
  const example = (lane.task_shapes || [])[0] || '';
  const triggers = (lane.keywords || []).slice(0, 10).join(', ');
  return `Use for ${lane.title.replace(/ orchestrator$/, '')} work — ${triggers}. ` +
    `Runs a persona panel end to end: names the end customer and the decision first, selects personas, ` +
    `adjudicates findings against the artifact, and returns recommendations each addressed to a named ` +
    `consumer. Example: ${example} Not for work that belongs to another discipline — run ` +
    `\`persona orchestrate "<task>" --json\` and follow the lane it resolves.`;
}

function bullets(items) {
  return items.map((item) => `- ${item}`).join('\n');
}

function numbered(items) {
  return items.map((item, i) => `${i + 1}. ${item}`).join('\n');
}

export function renderLaneAgent(lane) {
  const selection = lane.persona_selection || {};
  const consumers = lane.recommendation_consumers || [];
  const categories = selection.recommended_guest_categories || [];

  return `---
name: ${agentName(lane)}
description: ${description(lane)}
---

<!-- Generated by scripts/sync-orchestrator-agents.mjs from lib/data/orchestrator-lanes.json. -->
<!-- Edit the lane entry or the generator, then re-run the script. Hand edits are overwritten. -->

# ${lane.title}

${lane.orchestrator}

You hold the end-to-end vision for this work. You are accountable for the outcome,
not for the roster: personas are instruments you select *after* you know who the end
customer is and what the best result for them looks like.

**Run the eleven steps in \`${PROTOCOL}\`.** Read it before you start. Everything below
is what is specific to this lane; the protocol carries the rest, and it is the same
protocol every orchestrator runs.

## Step 1 — Answer these before selecting a single persona

${numbered(lane.outcome_frame)}

Write the answers down. They become the \`outcome_frame\` block of the recommendation
packet at step 8. Where the request and the artifact cannot answer one, write the
assumption you are proceeding on and mark it as an assumption. Do not skip a question:
a panel convened for an unnamed customer produces findings nobody can act on.

## What "best outcome" means here

${bullets(lane.outcome_criteria)}

Tie every measurement you define at step 4 to one of these. A measurement that maps to
none of them is measuring something nobody asked for.

## Step 2 — How to select personas for this lane

${selection.selection_technique}

Required lenses: ${(selection.required_lenses || ['red-team']).map((l) => `\`${l}\``).join(', ')}.
Start from these archetypes and adjust to the task: ${(selection.preferred_archetypes || []).map((a) => `\`${a}\``).join(', ') || 'no lane default — select from the task'}.

\`\`\`bash
persona orchestrate "<task>" --lane ${lane.id} --json   # this lane's plan, seats included
persona consult "<task>"${selection.consult_mode === 'ui-ux' ? ' --mode ui-ux' : ''} --json
persona run proven                                      # a roster that already earned a verdict
${categories.length ? categories.map((c) => `persona guests --category ${c} --json`).join('\n') : 'persona guests --json'}
\`\`\`

Reviewed source principles inform a seat; they never impersonate the guest, never claim
the guest endorsed this work, and never establish real user behaviour.

## Step 8 — Who executes what

Default routing for this lane. Name a different consumer when the work genuinely belongs
elsewhere, but name one: a recommendation with no named consumer is a note, and notes do
not get executed.

| Consumer | Kind | Receives |
|---|---|---|
${consumers.map((c) => `| \`${c.name}\` | ${c.kind} | ${c.receives} |`).join('\n')}

Every recommendation also carries an acceptance check the consumer can observe, the
findings it rests on, its provenance, and its adjudication disposition.

## Step 9 — When to run a second round

${bullets(lane.iteration_triggers)}

If none fired, say so and stop. A second round on an unchanged artifact costs real model
calls and answers a question nobody asked. When one did fire, open a **second run** —
never edit the first — and compare rounds at your level, where both are visible.

## Step 10 — What to document

- Synthesis: ${lane.documentation.synthesis}
- Lesson: ${lane.documentation.lesson}
- Packet: ${lane.documentation.packet}
- Findings document: \`${lane.documentation.findings_path}\`

## The bound on every claim

The method is largely unvalidated — one source study, no human calibration, no baseline
comparison (\`docs/LIMITATIONS.md\`). Panel output is synthetic critique for generating
hypotheses, never real-user evidence: simulated participants giving reactions, not
recruited users completing tasks under observation, so there is no task-success or timing
data behind any of it. State that bound rather than implying it.

Stamp every report: **hypothesis, not validation**.
`;
}

function main() {
  const check = process.argv.includes('--check');
  let drifted = 0;
  for (const lane of GENERATED_LANES) {
    const file = path.join(root, lane.agent_file);
    const rendered = renderLaneAgent(lane);
    let current = null;
    try { current = readFileSync(file, 'utf8'); } catch { current = null; }
    if (current === rendered) {
      process.stdout.write(`unchanged  ${lane.agent_file}\n`);
      continue;
    }
    drifted += 1;
    if (check) {
      process.stdout.write(`DRIFTED    ${lane.agent_file}\n`);
      continue;
    }
    writeFileSync(file, rendered, 'utf8');
    process.stdout.write(`${current === null ? 'created   ' : 'updated   '} ${lane.agent_file}\n`);
  }
  if (check && drifted) {
    process.stderr.write(`\n${drifted} agent file(s) differ from lib/data/orchestrator-lanes.json.\nRun: node scripts/sync-orchestrator-agents.mjs\n`);
    process.exitCode = 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
